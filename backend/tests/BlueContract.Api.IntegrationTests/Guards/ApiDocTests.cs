using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using BlueContract.Api.Auth;
using BlueContract.Api.IntegrationTests.Infrastructure;
using BlueContract.Domain.Identity;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Controllers;
using Microsoft.AspNetCore.Routing;
using Microsoft.Extensions.DependencyInjection;
using Shouldly;

namespace BlueContract.Api.IntegrationTests.Guards;

/// <summary>
/// AUDIT-1 §11.14: docs/API.md lists every endpoint of the running API — method, route, who may call it (permission),
/// body and result types, description from the XML comments. The list between the markers is generated from the
/// endpoint metadata; this test fails when it is stale. Regenerate: scripts/gen-api-doc.(ps1|sh).
/// </summary>
[Collection(ApiCollection.Name)]
public partial class ApiDocTests(ApiFactory factory)
{
    private const string Start = "<!-- api-endpoints:start (generated by scripts/gen-api-doc; do not edit by hand) -->";
    private const string End = "<!-- api-endpoints:end -->";

    [GeneratedRegex(@"\s+")]
    private static partial Regex Spaces();

    [Fact]
    public void Api_md_lists_every_endpoint_with_its_permission()
    {
        var path = Path.Combine(RepoRoot(), "docs", "API.md");
        File.Exists(path).ShouldBeTrue("docs/API.md is missing");
        var current = File.ReadAllText(path).ReplaceLineEndings("\n");
        var start = current.IndexOf(Start, StringComparison.Ordinal);
        var end = current.IndexOf(End, StringComparison.Ordinal);
        start.ShouldBeGreaterThanOrEqualTo(0, "start marker missing");
        end.ShouldBeGreaterThan(start, "end marker missing");

        var generated = Generate();
        var updated = current[..(start + Start.Length)] + "\n" + generated + current[end..];
        if (Environment.GetEnvironmentVariable("BLUEPROCURE_UPDATE_API_DOC") == "1")
        {
            File.WriteAllText(path, updated);
            return;
        }

        updated.ShouldBe(current, "docs/API.md is out of date: run scripts/gen-api-doc.ps1 (or .sh) and commit the result");
    }

    private string Generate()
    {
        var docs = XmlDocs();
        var names = PermissionCatalog.All.ToDictionary(p => p.Code, p => p.Name);
        var endpoints = factory.Services.GetRequiredService<EndpointDataSource>().Endpoints.OfType<RouteEndpoint>().ToList();
        var actions = endpoints
            .Select(e => (Endpoint: e, Action: e.Metadata.GetMetadata<ControllerActionDescriptor>()))
            .Where(x => x.Action is not null)
            .Select(x => (x.Endpoint, Action: x.Action!))
            .ToList();
        actions.ShouldNotBeEmpty();

        var sb = new StringBuilder();
        sb.Append(System.Globalization.CultureInfo.InvariantCulture, $"\n{actions.Count} endpoint, nhóm theo controller.\n");
        foreach (var group in actions.GroupBy(a => a.Action.ControllerTypeInfo).OrderBy(g => g.Key.Name, StringComparer.Ordinal))
        {
            var controller = group.Key;
            var title = controller.Name.Replace("Controller", string.Empty, StringComparison.Ordinal);
            sb.Append(System.Globalization.CultureInfo.InvariantCulture, $"\n### {title}\n\n");
            if (Summary(docs, "T:" + controller.FullName) is { } about)
            {
                sb.Append(about).Append("\n\n");
            }

            sb.Append("| Method | Đường dẫn | Quyền | Body → Kết quả | Mô tả |\n|---|---|---|---|---|\n");
            foreach (var (endpoint, action) in group.OrderBy(a => a.Endpoint.RoutePattern.RawText, StringComparer.Ordinal)
                         .ThenBy(a => Methods(a.Endpoint), StringComparer.Ordinal))
            {
                var method = action.MethodInfo;
                var description = Summary(docs, $"M:{method.DeclaringType!.FullName}.{method.Name}") ?? string.Empty;
                sb.Append(System.Globalization.CultureInfo.InvariantCulture,
                    $"| {Methods(endpoint)} | `/{endpoint.RoutePattern.RawText!.TrimStart('/')}` | {Access(endpoint, action, names)} | {Types(method)} | {Cell(description)} |\n");
            }
        }

        var others = endpoints.Where(e => e.Metadata.GetMetadata<ControllerActionDescriptor>() is null)
            .Select(e => "/" + e.RoutePattern.RawText!.TrimStart('/')).Distinct().Order(StringComparer.Ordinal).ToList();
        if (others.Count > 0)
        {
            sb.Append("\n### Khác (không qua controller)\n\n");
            foreach (var other in others)
            {
                sb.Append("- `").Append(other).Append("`\n");
            }
        }

        return sb.ToString();
    }

    private static string Methods(RouteEndpoint endpoint) =>
        string.Join(", ", endpoint.Metadata.GetMetadata<HttpMethodMetadata>()?.HttpMethods ?? ["ANY"]);

    /// <summary>"Công khai", "Đăng nhập", or the permissions (any of) with their Vietnamese names.</summary>
    private static string Access(RouteEndpoint endpoint, ControllerActionDescriptor action, Dictionary<string, string> names)
    {
        var metadata = endpoint.Metadata;
        if (action.FilterDescriptors.Any(f => f.Filter is ServiceFilterAttribute s && s.ServiceType.Name.Contains("HisInbound", StringComparison.Ordinal)))
        {
            return "HIS (API key + HMAC)";
        }

        if (endpoint.RoutePattern.RawText!.TrimStart('/').StartsWith("api/onlyoffice", StringComparison.Ordinal))
        {
            return "ONLYOFFICE (JWT)";
        }

        var permission = metadata.OfType<HasPermissionAttribute>().LastOrDefault();
        if (permission is not null)
        {
            return string.Join("<br>", permission.Permissions.Select(p => $"`{p}` {names.GetValueOrDefault(p, string.Empty)}".Trim()));
        }

        if (metadata.GetMetadata<IAllowAnonymous>() is not null)
        {
            return "Công khai";
        }

        return metadata.GetMetadata<IAuthorizeData>() is not null ? "Đăng nhập" : "Công khai";
    }

    private static string Types(MethodInfo method)
    {
        var body = method.GetParameters()
            .Where(p => p.GetCustomAttribute<FromBodyAttribute>() is not null
                || (p.ParameterType.IsClass && p.ParameterType != typeof(string) && p.ParameterType != typeof(CancellationToken)
                    && p.GetCustomAttribute<FromQueryAttribute>() is null && p.GetCustomAttribute<FromFormAttribute>() is null
                    && p.ParameterType.Name.EndsWith("Request", StringComparison.Ordinal)))
            .Select(p => TypeName(p.ParameterType)).FirstOrDefault();
        if (method.GetParameters().Any(p => p.ParameterType == typeof(IFormFile)))
        {
            body = "tệp (multipart)";
        }

        var result = method.ReturnType;
        if (result.IsGenericType && result.GetGenericTypeDefinition() == typeof(Task<>))
        {
            result = result.GetGenericArguments()[0];
        }

        if (result.IsGenericType && result.GetGenericTypeDefinition() == typeof(ActionResult<>))
        {
            result = result.GetGenericArguments()[0];
        }

        var output = result == typeof(Task) || typeof(IActionResult).IsAssignableFrom(result) ? "—" : TypeName(result);
        return body is null ? output : $"{body} → {output}";
    }

    private static string TypeName(Type type)
    {
        if (!type.IsGenericType)
        {
            return type.Name;
        }

        var name = type.Name[..type.Name.IndexOf('`', StringComparison.Ordinal)];
        return $"{name}&lt;{string.Join(", ", type.GetGenericArguments().Select(TypeName))}&gt;";
    }

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal);

    private static string? Summary(Dictionary<string, string> docs, string member)
    {
        if (docs.TryGetValue(member, out var exact))
        {
            return exact;
        }

        // Methods are keyed with their parameter list: take the first overload.
        return docs.Where(d => d.Key.StartsWith(member + "(", StringComparison.Ordinal)).Select(d => d.Value).FirstOrDefault();
    }

    private static Dictionary<string, string> XmlDocs()
    {
        var file = Path.ChangeExtension(typeof(Program).Assembly.Location, ".xml");
        if (!File.Exists(file))
        {
            return [];
        }

        return XDocument.Load(file).Descendants("member")
            .Where(m => m.Element("summary") is not null)
            .GroupBy(m => (string)m.Attribute("name")!)
            .ToDictionary(g => g.Key, g => Spaces().Replace(g.First().Element("summary")!.Nodes()
                .Select(n => n is XElement e ? (string?)e.Attribute("cref")?.Value.Split('.').Last() ?? (string?)e.Attribute("name") ?? e.Value : n is XText t ? t.Value : string.Empty)
                .Aggregate(string.Empty, (a, b) => a + b), " ").Trim());
    }

    private static string RepoRoot()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            if (Directory.Exists(Path.Combine(dir.FullName, "docs")) && Directory.Exists(Path.Combine(dir.FullName, "backend")))
            {
                return dir.FullName;
            }
        }

        throw new DirectoryNotFoundException("repository root not found above " + AppContext.BaseDirectory);
    }
}

internal sealed class SaveAcceptanceRequestValidator : AbstractValidator<SaveAcceptanceRequest>
{
    public SaveAcceptanceRequestValidator()
    {
        RuleFor(x => x.ContractId).NotEmpty().WithName("Hợp đồng");
        RuleFor(x => x.PeriodTo).GreaterThanOrEqualTo(x => x.PeriodFrom).WithMessage("Kỳ nghiệm thu: đến ngày phải sau từ ngày.");
        RuleFor(x => x.PeriodText).MaximumLength(100);
        RuleFor(x => x.Conclusion).MaximumLength(2000);
        RuleFor(x => x.ReceiptIds).NotEmpty().WithMessage("Chọn ít nhất một phiếu nhập kho.");
    }
}

internal sealed class SaveValuationRequestValidator : AbstractValidator<SaveValuationRequest>
{
    public SaveValuationRequestValidator()
    {
        RuleFor(x => x.ContractId).NotEmpty().WithName("Hợp đồng");
        RuleFor(x => x.AcceptanceIds).NotEmpty().WithMessage("Chọn ít nhất một biên bản nghiệm thu.");
        RuleFor(x => x.PeriodText).MaximumLength(100);
        RuleFor(x => x.AdvanceAmount).GreaterThanOrEqualTo(0).WithName("Giá trị tạm ứng");
        RuleFor(x => x.AdvanceRecovered).GreaterThanOrEqualTo(0).LessThanOrEqualTo(x => x.AdvanceAmount).WithName("Thu hồi tạm ứng");
    }
}

internal sealed class PaymentOrderRequestValidator : AbstractValidator<PaymentOrderRequest>
{
    public PaymentOrderRequestValidator()
    {
        RuleFor(x => x.Number).NotEmpty().MaximumLength(50).WithName("Số ủy nhiệm chi");
        RuleFor(x => x.Date).NotEmpty().WithName("Ngày ủy nhiệm chi");
        RuleFor(x => x.Amount).GreaterThan(0).WithName("Số tiền");
    }
}

internal sealed class SettlementRequestValidator : AbstractValidator<SettlementRequest>
{
    public SettlementRequestValidator()
    {
        RuleFor(x => x.Description).NotEmpty().MaximumLength(500).WithName("Nội dung");
        RuleFor(x => x.Amount).GreaterThan(0).WithName("Số tiền");
        RuleFor(x => x.VoucherNumber).MaximumLength(50);
    }
}

/// <summary>
/// Biên bản nghiệm thu (spec §6.5): job hằng tháng tự lập bản nháp theo từng hợp đồng từ các phiếu nhập kho đã ký đủ,
/// chưa nghiệm thu; Tổ Mua sắm cũng lập tay (chọn phiếu) → Rà soát → NCC ký → Giám đốc ký → Văn thư.
/// </summary>
public sealed class AcceptanceService(
    IAppDbContext db,
    DocumentNumbers numbers,
    PaymentDocumentData documentData,
    PaymentDocuments documents,
    ContractTracking tracking,
    NotificationService notifications,
    IAuditLogger audit,
    ICurrentUser current,
    DataScope dataScope,
    Workflows.WorkflowAccess workflowAccess)
{
    public const string OwnerType = "Acceptance";

    public async Task<PagedResult<AcceptanceListItemDto>> ListAsync(PageQuery q, AcceptanceFilter f, CancellationToken ct)
    {
        var query = db.AcceptanceRecords.AsNoTracking();
        if (await dataScope.ContractIdsAsync(ct) is { } scoped)
        {
            query = query.Where(x => scoped.Contains(x.ContractId));
        }

        if (!string.IsNullOrWhiteSpace(q.Search))
        {
            var p = PagingExtensions.LikePattern(q.Search);
            query = query.Where(a => EF.Functions.ILike(a.Number, p) || EF.Functions.ILike(a.PeriodText, p)
                || db.Contracts.Any(c => c.Id == a.ContractId && EF.Functions.ILike(c.Number, p)));
        }

        query = f.Status is { } status ? query.Where(a => a.Status == status) : query;
        query = f.ContractId is { } contract ? query.Where(a => a.ContractId == contract) : query;
        query = f.SupplierId is { } supplier ? query.Where(a => a.SupplierId == supplier) : query;
        query = f.Available == true ? query.Where(a => a.Status == PaymentRecordStatus.Completed && a.ValuationId == null) : query;

        return await query.OrderByDescending(a => a.CreatedAt).ThenByDescending(a => a.Id)
            .Select(a => new AcceptanceListItemDto(
                a.Id, a.Number, a.ContractId,
                db.Contracts.Where(c => c.Id == a.ContractId).Select(c => c.Number).FirstOrDefault() ?? string.Empty,
                a.SupplierId,
                db.Suppliers.Where(s => s.Id == a.SupplierId).Select(s => s.Name).FirstOrDefault() ?? string.Empty,
                a.PeriodText, a.PeriodFrom, a.PeriodTo, a.TotalAmount, a.Receipts.Count, a.Status, a.IsAutoGenerated, a.IsIncludedInValuation,
                db.ValuationRecords.Where(v => v.Id == a.ValuationId).Select(v => v.Number).FirstOrDefault(),
                a.CreatedAt))
            .ToPagedAsync(q, ct);
    }

    public async Task<Result<AcceptanceDto>> GetAsync(Guid id, CancellationToken ct)
    {
        var a = await db.AcceptanceRecords.AsNoTracking().Include(x => x.Receipts).Include(x => x.Items).FirstOrDefaultAsync(x => x.Id == id, ct);
        if (a is null || !await VisibleAsync(a.ContractId, a.DocumentId, ct))
        {
            return Error.NotFound();
        }

        var contract = await db.Contracts.AsNoTracking().Where(c => c.Id == a.ContractId).Select(c => new { c.Number, c.Name }).FirstAsync(ct);
        var supplier = await db.Suppliers.AsNoTracking().Where(s => s.Id == a.SupplierId).Select(s => s.Name).FirstOrDefaultAsync(ct);
        var valuation = a.ValuationId is { } vid ? await db.ValuationRecords.AsNoTracking().Where(v => v.Id == vid).Select(v => v.Number).FirstOrDefaultAsync(ct) : null;
        var manage = Manage;
        return new AcceptanceDto(a.Id, a.Number, a.ContractId, contract.Number, contract.Name, a.SupplierId, supplier ?? string.Empty, a.PeriodFrom, a.PeriodTo,
            a.PeriodText, a.Conclusion, a.IsAutoGenerated, a.TotalAmount, a.Status, a.DocumentId, a.LastReturnReason, a.CompletedAt, a.ValuationId, valuation,
            a.IsIncludedInValuation,
            [.. a.Receipts.OrderBy(r => r.Date).ThenBy(r => r.Number).Select(r => new AcceptanceReceiptDto(r.ReceiptId, r.Number, r.Date, r.Type, r.InvoiceNumber, r.Amount))],
            [.. a.Items.OrderBy(i => i.ItemCode).Select(i => new AcceptanceItemDto(i.ContractItemId, i.ItemCode, i.ItemName, i.Unit, i.Quantity, i.UnitPrice, i.Amount))],
            CanEdit: manage && a.IsEditable,
            CanSubmit: manage && a.IsEditable && a.DocumentId is not null,
            CanCancel: manage && a.IsEditable);
    }

    /// <summary>Phiếu nhập kho đã ký đủ, chưa nghiệm thu của hợp đồng (lọc theo khoảng ngày nếu có).</summary>
    public async Task<List<AcceptanceReceiptDto>> CandidatesAsync(Guid contractId, DateOnly? from, DateOnly? to, Guid? acceptanceId, CancellationToken ct)
    {
        if (!await dataScope.CanSeeContractAsync(contractId, ct))
        {
            return [];
        }

        var query = db.WarehouseReceipts.AsNoTracking()
            .Where(r => r.ContractId == contractId && r.Status == ReceiptStatus.Completed
                && (!r.IsIncludedInAcceptance || (acceptanceId != null && r.AcceptanceId == acceptanceId)));
        query = from is { } f ? query.Where(r => r.ReceiptDate >= f) : query;
        query = to is { } t ? query.Where(r => r.ReceiptDate <= t) : query;
        return await query.OrderBy(r => r.ReceiptDate).ThenBy(r => r.Number)
            .Select(r => new AcceptanceReceiptDto(r.Id, r.Number, r.ReceiptDate, r.Type, r.InvoiceNumber,
                r.Type == ReceiptType.Return ? -r.Lines.Sum(l => l.Amount) : r.Lines.Sum(l => l.Amount)))
            .ToListAsync(ct);
    }

    public async Task<Result<Guid>> CreateAsync(SaveAcceptanceRequest r, CancellationToken ct)
    {
        var contract = await db.Contracts.AsNoTracking().FirstOrDefaultAsync(c => c.Id == r.ContractId, ct);
        if (contract is null)
        {
            return Error.Validation("CONTRACT_NOT_FOUND");
        }

        if (contract.Status != ContractStatus.Effective)
        {
            return Error.Validation("CONTRACT_NOT_EFFECTIVE");
        }

        var acceptance = new AcceptanceRecord(await numbers.NextAsync(DocumentNumbers.Acceptance, ct), contract.Id, contract.SupplierId, r.PeriodFrom, r.PeriodTo,
            PeriodText(r.PeriodText, r.PeriodFrom, r.PeriodTo), isAutoGenerated: false);
        db.AcceptanceRecords.Add(acceptance);
        var applied = await ApplyAsync(acceptance, r.ReceiptIds, r.PeriodText, r.Conclusion, ct);
        if (!applied.IsSuccess)
        {
            return applied.Error!;
        }

        audit.Log("AcceptanceCreate", nameof(AcceptanceRecord), acceptance.Id.ToString(), new { acceptance.Number, contract = contract.Number, acceptance.TotalAmount });
        await db.SaveChangesAsync(ct);
        return acceptance.Id;
    }

    public async Task<Result> UpdateAsync(Guid id, SaveAcceptanceRequest r, CancellationToken ct)
    {
        var acceptance = await LoadAsync(id, ct);
        if (acceptance is null || acceptance.ContractId != r.ContractId)
        {
            return Result.Failure(Error.NotFound());
        }

        if (!acceptance.IsEditable)
        {
            return Result.Failure(Error.Conflict("ACCEPTANCE_LOCKED"));
        }

        var applied = await ApplyAsync(acceptance, r.ReceiptIds, r.PeriodText, r.Conclusion, ct);
        if (!applied.IsSuccess)
        {
            return applied;
        }

        await db.SaveChangesAsync(ct);
        return Result.Success();
    }

    public async Task<Result> SubmitAsync(Guid id, CancellationToken ct)
    {
        var acceptance = await LoadAsync(id, ct);
        if (acceptance?.DocumentId is not { } docId)
        {
            return Result.Failure(Error.NotFound());
        }

        if (!acceptance.IsEditable)
        {
            return Result.Failure(Error.Conflict("ACCEPTANCE_LOCKED"));
        }

        var submitted = await documents.SubmitAsync(docId, ct);
        if (!submitted.IsSuccess)
        {
            return submitted;
        }

        await db.SaveChangesAsync(ct);
        return Result.Success();
    }

    public async Task<Result> CancelAsync(Guid id, CancellationToken ct)
    {
        var acceptance = await LoadAsync(id, ct);
        if (acceptance is null)
        {
            return Result.Failure(Error.NotFound());
        }

        acceptance.Cancel();
        await ReleaseReceiptsAsync(acceptance, ct);
        await documents.CancelAsync(acceptance.DocumentId, "Hủy biên bản nghiệm thu", ct);
        audit.Log("AcceptanceCancel", nameof(AcceptanceRecord), acceptance.Id.ToString(), new { acceptance.Number });
        await db.SaveChangesAsync(ct);
        return Result.Success();
    }

    /// <summary>
    /// Job "ngày 1 hằng tháng" (spec §6.5): for the previous month, one draft per contract with signed receipts not yet
    /// accepted; the purchasing team is notified. Idempotent: receipts already in a draft are not taken again.
    /// </summary>
    public async Task<GenerateAcceptancesResultDto> GenerateMonthlyAsync(DateOnly runDate, CancellationToken ct)
    {
        var periodTo = new DateOnly(runDate.Year, runDate.Month, 1).AddDays(-1);
        var periodFrom = new DateOnly(periodTo.Year, periodTo.Month, 1);
        var periodText = "Tháng " + periodTo.ToString("MM/yyyy", CultureInfo.InvariantCulture);
        var groups = await db.WarehouseReceipts.AsNoTracking()
            .Where(r => r.Status == ReceiptStatus.Completed && !r.IsIncludedInAcceptance && r.ContractId != null && r.ReceiptDate <= periodTo)
            .GroupBy(r => r.ContractId!.Value)
            .Select(g => new { ContractId = g.Key, Receipts = g.Select(r => r.Id).ToList() })
            .ToListAsync(ct);

        var created = new List<string>();
        foreach (var group in groups)
        {
            var contract = await db.Contracts.AsNoTracking().FirstOrDefaultAsync(c => c.Id == group.ContractId && c.Status == ContractStatus.Effective, ct);
            if (contract is null)
            {
                continue;
            }

            var acceptance = new AcceptanceRecord(await numbers.NextAsync(DocumentNumbers.Acceptance, ct), contract.Id, contract.SupplierId, periodFrom, periodTo,
                periodText, isAutoGenerated: true);
            db.AcceptanceRecords.Add(acceptance);
            var applied = await ApplyAsync(acceptance, group.Receipts, periodText, null, ct);
            if (!applied.IsSuccess)
            {
                db.AcceptanceRecords.Remove(acceptance);
                continue;
            }

            created.Add(acceptance.Number);
            await db.SaveChangesAsync(ct);
        }

        if (created.Count > 0)
        {
            var buyers = await db.Users
                .Where(u => u.Status == UserStatus.Active && u.UserType == UserType.Internal
                    && u.Roles.Any(r => r.Role!.Permissions.Any(p => p.PermissionCode == Permissions.PaymentManage)))
                .Select(u => u.Id).ToListAsync(ct);
            await notifications.NotifyAsync(buyers, NotificationTypes.AcceptanceDrafted, $"Đã lập {created.Count} biên bản nghiệm thu nháp {periodText}",
                string.Join(", ", created), "/thanh-toan?tab=acceptance&status=Draft", email: true, ct);
            await db.SaveChangesAsync(ct);
        }

        return new GenerateAcceptancesResultDto(created.Count, created, periodText);
    }

    /// <summary>Takes the chosen receipts (signed, not yet accepted, of the contract), builds the item summary and the PDF.</summary>
    private async Task<Result> ApplyAsync(AcceptanceRecord acceptance, IReadOnlyCollection<Guid> receiptIds, string? periodText, string? conclusion, CancellationToken ct)
    {
        var ids = receiptIds.Distinct().ToList();
        var receipts = await db.WarehouseReceipts.Include(r => r.Lines)
            .Where(r => ids.Contains(r.Id) && r.ContractId == acceptance.ContractId).ToListAsync(ct);
        if (receipts.Count != ids.Count || receipts.Any(r => r.Status != ReceiptStatus.Completed))
        {
            return Result.Failure(Error.Validation("ACCEPTANCE_RECEIPT_NOT_ELIGIBLE"));
        }

        if (receipts.Any(r => r.IsIncludedInAcceptance && r.AcceptanceId != acceptance.Id))
        {
            return Result.Failure(Error.Conflict("RECEIPT_ALREADY_ACCEPTED"));
        }

        var contractItems = await db.Contracts.AsNoTracking().Where(c => c.Id == acceptance.ContractId).SelectMany(c => c.Items).ToDictionaryAsync(i => i.Id, ct);
        var items = receipts.SelectMany(r => r.Lines.Where(l => l.ContractItemId is not null)
                .Select(l => (Line: l, Quantity: r.Type == ReceiptType.Return ? -l.Quantity : l.Quantity)))
            .GroupBy(x => x.Line.ContractItemId!.Value)
            .Select(g =>
            {
                var item = contractItems[g.Key];
                return new AcceptanceItemDraft(g.Key, item.ItemCode, item.ItemName, item.Unit, g.Sum(x => x.Quantity), item.UnitPrice);
            }).ToList();

        await ReleaseReceiptsAsync(acceptance, ct, keep: ids);
        acceptance.SetContent(PeriodText(periodText ?? acceptance.PeriodText, acceptance.PeriodFrom, acceptance.PeriodTo), conclusion,
            [.. receipts.Select(r => new AcceptanceReceiptDraft(r.Id, r.Number, r.ReceiptDate, r.Type, r.InvoiceNumber, r.TotalAmount))], items);
        foreach (var receipt in receipts)
        {
            receipt.IncludeInAcceptance(acceptance.Id);
        }

        var rendered = await documents.RenderAsync(acceptance.DocumentId, TemplateKind.Acceptance, DocumentType.Acceptance, $"Biên bản nghiệm thu {acceptance.Number}",
            OwnerType, acceptance.Id, acceptance.SupplierId, acceptance.ContractId, await documentData.AcceptanceAsync(acceptance, ct),
            acceptance.DocumentId is null ? "Lập biên bản nghiệm thu" : "Cập nhật biên bản nghiệm thu", ct);
        if (!rendered.IsSuccess)
        {
            return Result.Failure(rendered.Error!);
        }

        acceptance.AttachDocument(rendered.Value);
        tracking.Defer(contractItems.Keys);
        return Result.Success();
    }

    private async Task ReleaseReceiptsAsync(AcceptanceRecord acceptance, CancellationToken ct, IReadOnlyCollection<Guid>? keep = null)
    {
        var held = await db.WarehouseReceipts.Where(r => r.AcceptanceId == acceptance.Id).ToListAsync(ct);
        foreach (var receipt in held.Where(r => keep is null || !keep.Contains(r.Id)))
        {
            receipt.ReleaseFromAcceptance(acceptance.Id);
        }
    }

    private Task<AcceptanceRecord?> LoadAsync(Guid id, CancellationToken ct) =>
        db.AcceptanceRecords.Include(x => x.Receipts).Include(x => x.Items).FirstOrDefaultAsync(x => x.Id == id, ct);

    private bool Manage => !current.IsSupplier && current.HasPermission(Permissions.PaymentManage);

    private static string PeriodText(string? text, DateOnly from, DateOnly to) =>
        !string.IsNullOrWhiteSpace(text) ? text.Trim()
        : from.Day == 1 && to == from.AddMonths(1).AddDays(-1) ? "Tháng " + from.ToString("MM/yyyy", CultureInfo.InvariantCulture)
        : $"Từ {from.ToString("dd/MM/yyyy", CultureInfo.InvariantCulture)} đến {to.ToString("dd/MM/yyyy", CultureInfo.InvariantCulture)}";

    /// <summary>Data scope (spec §4.2): out-of-scope records look missing, unless the user takes part in their signing.</summary>
    private async Task<bool> VisibleAsync(Guid contractId, Guid? documentId, CancellationToken ct) =>
        await dataScope.CanSeeContractAsync(contractId, ct) || (documentId is { } doc && await workflowAccess.IsParticipantAsync(doc, ct));
}

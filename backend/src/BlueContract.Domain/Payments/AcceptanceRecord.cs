using BlueContract.Domain.Common;
using BlueContract.Domain.Receipts;
using BlueContract.Domain.Workflows;

namespace BlueContract.Domain.Payments;

/// <summary>Trạng thái chung của biên bản nghiệm thu / 08a / thanh lý (theo luồng ký).</summary>
public enum PaymentRecordStatus
{
    Draft = 0,
    Signing = 1,
    Returned = 2,
    Completed = 3,
    Cancelled = 4,
}

public sealed record AcceptanceReceiptDraft(Guid ReceiptId, string Number, DateOnly Date, ReceiptType Type, string? InvoiceNumber, decimal Amount);

public sealed record AcceptanceItemDraft(Guid ContractItemId, string ItemCode, string ItemName, string Unit, decimal Quantity, decimal UnitPrice);

/// <summary>
/// Biên bản nghiệm thu (spec §5.6, §6.5): one contract, one period, the signed receipts (hoàn trả trừ đi) not yet accepted.
/// Created as a draft by the monthly job or by Tổ Mua sắm, then Rà soát → NCC → Giám đốc → Văn thư.
/// </summary>
public sealed class AcceptanceRecord : Entity, ISupplierScoped
{
    private readonly List<AcceptanceReceipt> _receipts = [];
    private readonly List<AcceptanceItem> _items = [];

    private AcceptanceRecord()
    {
        Number = string.Empty;
        PeriodText = string.Empty;
    }

    public AcceptanceRecord(string number, Guid contractId, Guid supplierId, DateOnly periodFrom, DateOnly periodTo, string periodText, bool isAutoGenerated)
    {
        if (periodTo < periodFrom)
        {
            throw new DomainException("ACCEPTANCE_PERIOD_INVALID");
        }

        Number = Guard.Required(number, "ACCEPTANCE_NUMBER_REQUIRED");
        ContractId = contractId;
        SupplierId = supplierId;
        PeriodFrom = periodFrom;
        PeriodTo = periodTo;
        PeriodText = Guard.Required(periodText, "ACCEPTANCE_PERIOD_INVALID");
        IsAutoGenerated = isAutoGenerated;
        Status = PaymentRecordStatus.Draft;
    }

    public string Number { get; private set; }

    public Guid ContractId { get; private set; }

    public Guid SupplierId { get; private set; }

    public DateOnly PeriodFrom { get; private set; }

    public DateOnly PeriodTo { get; private set; }

    public string PeriodText { get; private set; }

    /// <summary>Tạo bởi job nghiệm thu hằng tháng.</summary>
    public bool IsAutoGenerated { get; private set; }

    public string? Conclusion { get; private set; }

    public PaymentRecordStatus Status { get; private set; }

    public Guid? DocumentId { get; private set; }

    public string? LastReturnReason { get; private set; }

    public DateTimeOffset? CompletedAt { get; private set; }

    /// <summary>Biên bản 08a đang dùng biên bản này (giữ chỗ từ khi lập 08a).</summary>
    public Guid? ValuationId { get; private set; }

    /// <summary>Đã đưa vào thanh toán (08a đã ký xong).</summary>
    public bool IsIncludedInValuation { get; private set; }

    /// <summary>Giá trị nghiệm thu (hoàn trả mang dấu âm).</summary>
    public decimal TotalAmount { get; private set; }

    public IReadOnlyCollection<AcceptanceReceipt> Receipts => _receipts;

    public IReadOnlyCollection<AcceptanceItem> Items => _items;

    public bool IsEditable => Status is PaymentRecordStatus.Draft or PaymentRecordStatus.Returned;

    public void SetContent(string periodText, string? conclusion, IReadOnlyCollection<AcceptanceReceiptDraft> receipts, IReadOnlyCollection<AcceptanceItemDraft> items)
    {
        EnsureEditable();
        if (receipts.Count == 0)
        {
            throw new DomainException("ACCEPTANCE_RECEIPTS_REQUIRED");
        }

        if (receipts.GroupBy(r => r.ReceiptId).Any(g => g.Count() > 1))
        {
            throw new DomainException("ACCEPTANCE_RECEIPT_DUPLICATE");
        }

        PeriodText = Guard.Required(periodText, "ACCEPTANCE_PERIOD_INVALID");
        Conclusion = Guard.Optional(conclusion);
        _receipts.Clear();
        _receipts.AddRange(receipts.Select(r => new AcceptanceReceipt(Id, r)));
        _items.Clear();
        _items.AddRange(items.Where(i => i.Quantity != 0).Select(i => new AcceptanceItem(Id, i)));
        TotalAmount = _receipts.Sum(r => r.Amount);
        if (TotalAmount <= 0)
        {
            throw new DomainException("ACCEPTANCE_AMOUNT_INVALID");
        }
    }

    public void AttachDocument(Guid documentId) => DocumentId = documentId;

    public void ApplyWorkflow(WorkflowStatus workflowStatus, string? returnReason, DateTimeOffset now)
    {
        if (Status == PaymentRecordStatus.Cancelled)
        {
            return;
        }

        (Status, CompletedAt, LastReturnReason) = workflowStatus switch
        {
            WorkflowStatus.Running => (PaymentRecordStatus.Signing, CompletedAt, LastReturnReason),
            WorkflowStatus.Returned => (PaymentRecordStatus.Returned, CompletedAt, returnReason),
            WorkflowStatus.Completed => (PaymentRecordStatus.Completed, CompletedAt ?? now, LastReturnReason),
            WorkflowStatus.Cancelled => (PaymentRecordStatus.Draft, CompletedAt, LastReturnReason),
            _ => (Status, CompletedAt, LastReturnReason),
        };
    }

    public void Cancel()
    {
        if (Status == PaymentRecordStatus.Completed || ValuationId is not null)
        {
            throw new DomainException("ACCEPTANCE_NOT_CANCELLABLE");
        }

        Status = PaymentRecordStatus.Cancelled;
    }

    /// <summary>Giữ chỗ cho một biên bản 08a (chỉ biên bản đã ký, chưa đưa vào thanh toán).</summary>
    public void ReserveForValuation(Guid valuationId)
    {
        if (Status != PaymentRecordStatus.Completed)
        {
            throw new DomainException("ACCEPTANCE_NOT_COMPLETED");
        }

        if (ValuationId is not null && ValuationId != valuationId)
        {
            throw new DomainException("ACCEPTANCE_ALREADY_IN_VALUATION");
        }

        ValuationId = valuationId;
    }

    public void ConfirmInValuation(Guid valuationId)
    {
        if (ValuationId == valuationId)
        {
            IsIncludedInValuation = true;
        }
    }

    public void ReleaseFromValuation(Guid valuationId)
    {
        if (ValuationId == valuationId)
        {
            ValuationId = null;
            IsIncludedInValuation = false;
        }
    }

    private void EnsureEditable()
    {
        if (!IsEditable)
        {
            throw new DomainException("ACCEPTANCE_LOCKED");
        }
    }
}

public sealed class AcceptanceReceipt
{
    private AcceptanceReceipt()
    {
        Number = string.Empty;
    }

    internal AcceptanceReceipt(Guid acceptanceId, AcceptanceReceiptDraft d)
    {
        Id = Guid.CreateVersion7();
        AcceptanceId = acceptanceId;
        ReceiptId = d.ReceiptId;
        Number = d.Number;
        Date = d.Date;
        Type = d.Type;
        InvoiceNumber = d.InvoiceNumber;
        Amount = d.Type == ReceiptType.Return ? -Math.Abs(d.Amount) : Math.Abs(d.Amount);
    }

    public Guid Id { get; private set; }

    public Guid AcceptanceId { get; private set; }

    public Guid ReceiptId { get; private set; }

    public string Number { get; private set; }

    public DateOnly Date { get; private set; }

    public ReceiptType Type { get; private set; }

    public string? InvoiceNumber { get; private set; }

    /// <summary>Giá trị phiếu (hoàn trả âm).</summary>
    public decimal Amount { get; private set; }
}

/// <summary>Tổng hợp hàng hóa của biên bản (SL thuần = nhập − hoàn trả) theo mặt hàng hợp đồng.</summary>
public sealed class AcceptanceItem
{
    private AcceptanceItem()
    {
        ItemCode = string.Empty;
        ItemName = string.Empty;
        Unit = string.Empty;
    }

    internal AcceptanceItem(Guid acceptanceId, AcceptanceItemDraft d)
    {
        Id = Guid.CreateVersion7();
        AcceptanceId = acceptanceId;
        ContractItemId = d.ContractItemId;
        ItemCode = d.ItemCode;
        ItemName = d.ItemName;
        Unit = d.Unit;
        Quantity = d.Quantity;
        UnitPrice = d.UnitPrice;
        Amount = decimal.Round(d.Quantity * d.UnitPrice, 0, MidpointRounding.AwayFromZero);
    }

    public Guid Id { get; private set; }

    public Guid AcceptanceId { get; private set; }

    public Guid ContractItemId { get; private set; }

    public string ItemCode { get; private set; }

    public string ItemName { get; private set; }

    public string Unit { get; private set; }

    public decimal Quantity { get; private set; }

    public decimal UnitPrice { get; private set; }

    public decimal Amount { get; private set; }
}

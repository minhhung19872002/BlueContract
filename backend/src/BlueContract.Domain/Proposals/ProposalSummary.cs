using BlueContract.Domain.Common;
using BlueContract.Domain.Identity;
using BlueContract.Domain.Workflows;

namespace BlueContract.Domain.Proposals;

public enum ProposalSummaryStatus
{
    Draft = 0,
    AggregatorSigning = 1,
    DomainHeadReview = 2,
    DirectorSigning = 3,

    /// <summary>Giám đốc đã ký: cơ sở để gọi hàng.</summary>
    Approved = 4,
    Returned = 5,
    Cancelled = 6,
}

public sealed record SummaryLineDraft(
    Guid ContractId,
    string ContractNumber,
    Guid ContractItemId,
    Guid SupplierId,
    string SupplierName,
    string ItemCode,
    string ItemName,
    string Unit,
    decimal UnitPrice,
    decimal ProposedQuantity,
    decimal OpeningStock,
    decimal Received,
    decimal Issued,
    decimal CurrentStock,
    decimal ContractRemaining);

/// <summary>
/// Phiếu tổng hợp đề xuất (spec §5.4, §6.2 B2–B3): proposals of one domain merged by contract item; the domain head may
/// change the approved quantities; once the director signs it is the basis for call orders (Σ gọi ≤ SL duyệt).
/// </summary>
public sealed class ProposalSummary : Entity
{
    private readonly List<ProposalSummaryLine> _lines = [];
    private readonly List<ProposalSummarySource> _sources = [];

    private ProposalSummary()
    {
        Number = string.Empty;
        PeriodText = string.Empty;
    }

    public ProposalSummary(string number, ProcurementDomain domain, Guid? facilityId, string periodText, Guid aggregatorId, string? aggregatorName)
    {
        Number = Guard.Required(number, "SUMMARY_NUMBER_REQUIRED");
        Domain = domain;
        FacilityId = facilityId;
        PeriodText = Guard.Required(periodText, "SUMMARY_PERIOD_REQUIRED");
        AggregatorId = aggregatorId;
        AggregatorName = aggregatorName;
        Status = ProposalSummaryStatus.Draft;
    }

    public string Number { get; private set; }

    public ProcurementDomain Domain { get; private set; }

    public Guid? FacilityId { get; private set; }

    public string PeriodText { get; private set; }

    public Guid AggregatorId { get; private set; }

    public string? AggregatorName { get; private set; }

    public string? Note { get; private set; }

    public ProposalSummaryStatus Status { get; private set; }

    public Guid? DocumentId { get; private set; }

    public DateTimeOffset? ApprovedAt { get; private set; }

    public IReadOnlyCollection<ProposalSummaryLine> Lines => _lines;

    public IReadOnlyCollection<ProposalSummarySource> Sources => _sources;

    public bool IsEditable => Status is ProposalSummaryStatus.Draft or ProposalSummaryStatus.Returned;

    public void SetContent(IReadOnlyCollection<Guid> proposalIds, IReadOnlyCollection<SummaryLineDraft> lines, string? note)
    {
        if (!IsEditable)
        {
            throw new DomainException("SUMMARY_LOCKED");
        }

        if (proposalIds.Count == 0 || lines.Count == 0)
        {
            throw new DomainException("SUMMARY_PROPOSALS_REQUIRED");
        }

        _sources.Clear();
        _sources.AddRange(proposalIds.Distinct().Select(p => new ProposalSummarySource(Id, p)));
        _lines.Clear();
        _lines.AddRange(lines.Select(l => new ProposalSummaryLine(Id, l)));
        Note = Guard.Optional(note);
    }

    /// <summary>Tổ trưởng sửa SL duyệt (only while reviewing; a signed version is regenerated by the caller).</summary>
    public void SetApprovedQuantity(Guid lineId, decimal approved)
    {
        if (Status != ProposalSummaryStatus.DomainHeadReview)
        {
            throw new DomainException("SUMMARY_NOT_IN_REVIEW");
        }

        var line = _lines.FirstOrDefault(l => l.Id == lineId) ?? throw new DomainException("SUMMARY_LINE_NOT_FOUND");
        line.SetApproved(approved);
    }

    public void AttachDocument(Guid documentId) => DocumentId = documentId;

    public void ApplyWorkflow(WorkflowStatus status, WorkflowStepInstance? active, DateTimeOffset now)
    {
        if (Status == ProposalSummaryStatus.Cancelled)
        {
            return;
        }

        Status = status switch
        {
            WorkflowStatus.Completed => ProposalSummaryStatus.Approved,
            WorkflowStatus.Returned => ProposalSummaryStatus.Returned,
            WorkflowStatus.Cancelled => ProposalSummaryStatus.Draft,
            _ => active?.ActionType switch
            {
                WorkflowActionType.Approve or WorkflowActionType.Review => ProposalSummaryStatus.DomainHeadReview,
                WorkflowActionType.Sign when active.AssigneeType == AssigneeType.Creator => ProposalSummaryStatus.AggregatorSigning,
                WorkflowActionType.Sign => ProposalSummaryStatus.DirectorSigning,
                _ => Status,
            },
        };

        if (Status == ProposalSummaryStatus.Approved)
        {
            ApprovedAt ??= now;
        }
    }

    /// <summary>Records a call against a line: Σ gọi các lần ≤ SL duyệt (spec §5.4).</summary>
    public void RegisterCall(Guid lineId, decimal quantity)
    {
        if (Status != ProposalSummaryStatus.Approved)
        {
            throw new DomainException("SUMMARY_NOT_APPROVED");
        }

        var line = _lines.FirstOrDefault(l => l.Id == lineId) ?? throw new DomainException("SUMMARY_LINE_NOT_FOUND");
        line.Call(quantity);
    }

    /// <summary>Gives back quantity the supplier could not deliver (confirmed less / rejected / order cancelled).</summary>
    public void ReleaseCall(Guid lineId, decimal quantity) =>
        (_lines.FirstOrDefault(l => l.Id == lineId) ?? throw new DomainException("SUMMARY_LINE_NOT_FOUND")).Release(quantity);

    public void Cancel()
    {
        if (Status == ProposalSummaryStatus.Approved && _lines.Any(l => l.CalledQuantity > 0))
        {
            throw new DomainException("SUMMARY_ALREADY_CALLED");
        }

        Status = ProposalSummaryStatus.Cancelled;
    }
}

public sealed class ProposalSummarySource
{
    private ProposalSummarySource()
    {
    }

    internal ProposalSummarySource(Guid summaryId, Guid proposalId)
    {
        SummaryId = summaryId;
        ProposalId = proposalId;
    }

    public Guid SummaryId { get; private set; }

    public Guid ProposalId { get; private set; }
}

public sealed class ProposalSummaryLine
{
    private ProposalSummaryLine()
    {
        ContractNumber = string.Empty;
        SupplierName = string.Empty;
        ItemCode = string.Empty;
        ItemName = string.Empty;
        Unit = string.Empty;
    }

    internal ProposalSummaryLine(Guid summaryId, SummaryLineDraft d)
    {
        Id = Guid.CreateVersion7();
        SummaryId = summaryId;
        ContractId = d.ContractId;
        ContractNumber = d.ContractNumber;
        ContractItemId = d.ContractItemId;
        SupplierId = d.SupplierId;
        SupplierName = d.SupplierName;
        ItemCode = d.ItemCode;
        ItemName = d.ItemName;
        Unit = d.Unit;
        UnitPrice = d.UnitPrice;
        ProposedQuantity = d.ProposedQuantity;
        OpeningStock = d.OpeningStock;
        Received = d.Received;
        Issued = d.Issued;
        CurrentStock = d.CurrentStock;
        ContractRemaining = d.ContractRemaining;
        ApprovedQuantity = Math.Min(d.ProposedQuantity, d.ContractRemaining);
    }

    public Guid Id { get; private set; }

    public Guid SummaryId { get; private set; }

    public Guid ContractId { get; private set; }

    public string ContractNumber { get; private set; }

    public Guid ContractItemId { get; private set; }

    public Guid SupplierId { get; private set; }

    public string SupplierName { get; private set; }

    public string ItemCode { get; private set; }

    public string ItemName { get; private set; }

    public string Unit { get; private set; }

    public decimal UnitPrice { get; private set; }

    /// <summary>Tổng SL đề xuất của các khoa.</summary>
    public decimal ProposedQuantity { get; private set; }

    public decimal OpeningStock { get; private set; }

    public decimal Received { get; private set; }

    public decimal Issued { get; private set; }

    public decimal CurrentStock { get; private set; }

    public decimal ContractRemaining { get; private set; }

    /// <summary>SL tổ trưởng duyệt (mặc định = SL đề xuất, không vượt SL còn lại của hợp đồng).</summary>
    public decimal ApprovedQuantity { get; private set; }

    public decimal CalledQuantity { get; private set; }

    public decimal RemainingToCall => ApprovedQuantity - CalledQuantity;

    public decimal Amount => decimal.Round(ApprovedQuantity * UnitPrice, 0, MidpointRounding.AwayFromZero);

    internal void SetApproved(decimal approved)
    {
        if (approved < 0)
        {
            throw new DomainException("SUMMARY_APPROVED_INVALID");
        }

        if (approved > ContractRemaining)
        {
            throw new DomainException("SUMMARY_APPROVED_EXCEEDS_CONTRACT");
        }

        ApprovedQuantity = approved;
    }

    internal void Call(decimal quantity)
    {
        if (quantity <= 0)
        {
            throw new DomainException("CALL_QUANTITY_INVALID");
        }

        if (CalledQuantity + quantity > ApprovedQuantity)
        {
            throw new DomainException("CALL_QTY_EXCEEDS_APPROVED");
        }

        CalledQuantity += quantity;
    }

    internal void Release(decimal quantity) => CalledQuantity = Math.Max(0, CalledQuantity - quantity);
}
